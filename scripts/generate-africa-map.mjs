import { writeFile, mkdir } from 'node:fs/promises';
import { dirname } from 'node:path';
import { geoNaturalEarth1, geoPath } from 'd3-geo';
import { union } from '@turf/union';
import { featureCollection } from '@turf/helpers';

function reverseRingsForD3(feature) {
  const geometry = feature.geometry;

  if (!geometry) {
    throw new Error('Africa geometry is missing.');
  }

  const reverseRing = (ring) => [...ring].reverse();

  if (geometry.type === 'Polygon') {
    return {
      ...feature,
      geometry: {
        ...geometry,
        coordinates: geometry.coordinates.map(reverseRing),
      },
    };
  }

  if (geometry.type === 'MultiPolygon') {
    return {
      ...feature,
      geometry: {
        ...geometry,
        coordinates: geometry.coordinates.map((polygon) =>
          polygon.map(reverseRing)
        ),
      },
    };
  }

  throw new Error(`Unsupported geometry type: ${geometry.type}`);
}

const SOURCE = 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_10m_admin_0_countries.geojson';
const WIDTH = 1000;
const HEIGHT = 1000;
const HUBS = [
  { name: 'Dakar', coordinates: [-17.4677, 14.7167], strength: 0.55 },
  { name: 'Accra', coordinates: [-0.1870, 5.6037], strength: 0.65 },
  { name: 'Lagos', coordinates: [3.3792, 6.5244], strength: 1.0 },
  { name: 'Kinshasa', coordinates: [15.2663, -4.4419], strength: 0.55 },
  { name: 'Cairo', coordinates: [31.2357, 30.0444], strength: 0.6 },
  { name: 'Addis Ababa', coordinates: [38.7578, 8.9806], strength: 0.65 },
  { name: 'Nairobi', coordinates: [36.8219, -1.2921], strength: 0.9 },
  { name: 'Johannesburg', coordinates: [28.0473, -26.2041], strength: 1.0 },
  { name: 'Cape Town', coordinates: [18.4241, -33.9249], strength: 0.5 },
];

const response = await fetch(SOURCE);
if (!response.ok) throw new Error(`Could not download Natural Earth GeoJSON (${response.status}).`);
const world = await response.json();
const africanCountries = world.features.filter(
  (feature) => feature.properties?.CONTINENT === 'Africa'
    && ['Polygon', 'MultiPolygon'].includes(feature.geometry?.type)
);
if (!africanCountries.length) throw new Error('No African country geometries were found in the source dataset.');

// Dissolve country polygons into one continuous continental feature.
const dissolved = union(featureCollection(africanCountries));
if (!dissolved?.geometry) throw new Error('The African country geometries could not be dissolved.');

// D3 uses spherical polygon winding conventions, which are
// opposite to the RFC 7946 GeoJSON convention.
const africaForD3 = reverseRingsForD3(dissolved);

// Fit the corrected African geometry, not the original geometry.
const projection = geoNaturalEarth1().fitExtent(
  [[34, 34], [966, 966]],
  africaForD3
);

const pathGenerator = geoPath(projection);

const africaPath = pathGenerator(africaForD3);

if (!africaPath) {
  throw new Error('Failed to generate the Africa SVG path.');
}

const projectedHubs = HUBS.map((hub) => {
  const point = projection(hub.coordinates);
  if (!point) throw new Error(`Could not project hub: ${hub.name}`);
  return { name: hub.name, x: Number(point[0].toFixed(2)), y: Number(point[1].toFixed(2)), strength: hub.strength };
});

const svg = `<?xml version="1.0" encoding="UTF-8"?>\n<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${WIDTH} ${HEIGHT}" role="img" aria-label="Silhouette of the African continent">\n  <path d="${africaPath}" fill="#ffffff" fill-rule="evenodd"/>\n</svg>\n`;
const ts = `// Generated by scripts/generate-africa-map.mjs. Do not edit by hand.\nexport const AFRICA_VIEWBOX = { width: ${WIDTH}, height: ${HEIGHT} } as const;\nexport const AFRICA_PATH = ${JSON.stringify(africaPath)};\nexport const AFRICA_HUBS = ${JSON.stringify(projectedHubs, null, 2)} as const;\n`;

const outputs = [
  ['public/maps/africa-silhouette.svg', svg],
  ['src/app/component/home-motif/africa-map.generated.ts', ts],
];
for (const [file, content] of outputs) {
  await mkdir(dirname(file), { recursive: true });
  await writeFile(file, content, 'utf8');
  console.log(`Generated ${file}`);
}
console.log(`Dissolved ${africanCountries.length} African country geometries into one SVG silhouette.`);
